import assert from 'node:assert/strict';
import { calculateCbtBlockProgress, selectContinuousPastQuestions, roundQuestionCount } from '../src/utils/continuousCbt.js';
import { createStudyClock, tickStudyClock, studyDayEndsAt } from '../src/utils/studyClock.js';
import { upsertStudySession, dailyCbtProgress, applyDailyCbtProgress } from '../src/utils/cbtStudyLedger.js';
import { createDefaultPartnerState, buildDeterministicPlan, createPlanVersion, getActivePartnerPlan, rolloverPartnerDay, validatePartnerPlan, mergeAiPlan, adjustTodayPlanItem, setPartnerDayOff, availableMinutesForDate } from '../src/utils/aiPartner.js';

const early = calculateCbtBlockProgress({ targetMinutes:75, elapsedSeconds:720, answeredCount:15, forceComplete:true });
assert.equal(early.completedMinutes,12);
assert.equal(early.endedEarly,true);
assert.equal(early.progressPercent,16);
assert.equal(calculateCbtBlockProgress({targetMinutes:75,elapsedSeconds:4500,answeredCount:0}).completedMinutes,0);
assert.equal(calculateCbtBlockProgress({targetMinutes:75,elapsedSeconds:4500,answeredCount:15}).completed,true);
assert.equal(roundQuestionCount(3),3);
assert.equal(roundQuestionCount(75),15);
assert.equal(roundQuestionCount(3,[{answered:15,durationSeconds:1800}]),1);
let clock=createStudyClock(0,0);
clock=tickStudyClock(clock,{now:30000,active:true,visible:true}); assert.equal(clock.seconds,30);
clock=tickStudyClock(clock,{now:3600000,active:true,visible:false}); assert.equal(clock.seconds,30,'숨겨진 탭은 학습시간에서 제외');
clock=tickStudyClock({...clock,lastInteraction:3600000},{now:3610000,active:true,visible:true}); assert.equal(clock.seconds,40);
clock=tickStudyClock(clock,{now:4000000,active:true,visible:true}); assert.equal(clock.seconds,150,'2분 이상 입력이 없으면 방치시간 제외');
clock=tickStudyClock(clock,{now:4100000,active:false,visible:true}); assert.equal(clock.seconds,150);
clock=tickStudyClock({...clock,lastInteraction:4100000},{now:4110000,active:true,visible:true,submitted:true}); assert.equal(clock.seconds,150);
const midnight=studyDayEndsAt('2026-09-30');
assert.equal(tickStudyClock(createStudyClock(0,midnight-10000),{now:midnight+30000,active:true,visible:true,stopAt:midnight}).seconds,10,'자정 이후의 시간을 전날 목표에 합산하지 않는다');

const questions=Array.from({length:50},(_,i)=>({id:`q${i}`,question:`고유 기출 문제 ${i}`,choices:['가','나','다','라'],answerIndex:0,subject:'전기이론',topic:i<15?'교류회로':'전동기'}));
const wrong={...questions[0],questionId:'q0',isCorrect:false,lastSolvedAt:100};
const next=selectContinuousPastQuestions({questions,progress:[wrong],seenQuestionIds:['q0'],recentWrongQuestions:[questions[0]],limit:15});
assert.ok(next.questionIds.includes('q0'),'미풀이가 많아도 방금 오답 복습');
assert.equal(next.questionIds.length,15); assert.equal(new Set(next.questionIds).size,15); assert.ok(next.unseenCount>0);
const corrected=selectContinuousPastQuestions({questions,progress:[{...wrong,isCorrect:true,nextReviewAt:99999999}],seenQuestionIds:['q0'],recentWrongQuestions:[questions[0]],limit:15,now:200});
assert.ok(!corrected.questionIds.includes('q0'),'교정된 과거 오답 제외');
assert.equal(selectContinuousPastQuestions({questions:[{...questions[0],answerIndex:7},{...questions[1],choices:[]}]}).questions.length,0);
assert.equal(selectContinuousPastQuestions({questions:[questions[0],{...questions[0],id:'another'}]}).questions.length,1);
assert.equal(selectContinuousPastQuestions({questions:questions.slice(0,2),seenQuestionIds:['q0','q1']}).questions.length,2);

const row={sessionId:'session1',goalId:'c1',date:'2026-09-30',answered:15,answeredIds:['q0'],durationSeconds:720,submitted:true};
let ledger=upsertStudySession([],row); ledger=upsertStudySession(ledger,row);
assert.equal(dailyCbtProgress(ledger,'c1','2026-09-30',75).completedMinutes,12,'중복 저장은 중복 합산하지 않는다');
ledger=upsertStudySession(ledger,{...row,durationSeconds:600,answered:10}); assert.equal(ledger[0].durationSeconds,720);
ledger=upsertStudySession(ledger,{...row,endedEarly:true});
assert.equal(dailyCbtProgress(ledger,'c1','2026-09-30',75).status,'completed');
assert.equal(dailyCbtProgress(ledger,'c1','2026-09-30',75).completedMinutes,12);
assert.equal(dailyCbtProgress(ledger,'c1','2026-10-01',75).completedMinutes,0);
assert.equal(dailyCbtProgress(ledger,'c2','2026-09-30',75).completedMinutes,0);
const state=createDefaultPartnerState();
state.profile.dailyAvailableMinutes={mon:90,tue:90,wed:90,thu:90,fri:90,sat:120,sun:120};
state.certificateGoals=[{id:'c1',name:'전기기능사',startDate:'2026-09-30',examDate:'2026-10-10'},{id:'c2',name:'전자기능사',startDate:'2026-09-30',examDate:'2026-10-10'}];
state.certificateGoal=state.certificateGoals[0];
const plan=buildDeterministicPlan(state,{today:'2026-09-30'});
assert.equal(new Set(plan.today.items.map(i=>i.goalId)).size,2,'두 자격증의 독립 학습'); assert.ok(plan.today.totalMinutes<=90);
assert.ok(plan.today.items.every(i=>i.durationMinutes>=15));
const restored=applyDailyCbtProgress(plan,ledger); assert.equal(restored.today.items.find(i=>i.goalId==='c1').result.completedMinutes,12);
assert.equal(restored.today.items.find(i=>i.goalId==='c2').status,'todo');
state.cbtStudySessions=ledger;
let activeState=createPlanVersion(state,plan,{activate:true});
assert.equal(getActivePartnerPlan(activeState).today.items.find(i=>i.goalId==='c1').result.completedMinutes,12);
activeState=rolloverPartnerDay(activeState,{today:'2026-10-01'});
assert.equal(getActivePartnerPlan(activeState).today.date,'2026-10-01');
assert.equal(getActivePartnerPlan(activeState).today.items.find(i=>i.goalId==='c1').status,'todo');
const future={...state,certificateGoals:state.certificateGoals.map(g=>({...g,startDate:'2026-10-02'}))};
assert.equal(buildDeterministicPlan(future,{today:'2026-09-30'}).today.items.length,0,'같은 주여도 시작일 전 배치 금지');
assert.equal(getActivePartnerPlan(rolloverPartnerDay(activeState,{today:'2026-10-11'})).today.items.length,0,'마감 지난 일 이월 금지');
const zero={...state,profile:{...state.profile,dailyAvailableMinutes:{...state.profile.dailyAvailableMinutes,wed:0}}};
assert.equal(buildDeterministicPlan(zero,{today:'2026-09-30'}).today.items.length,0);
assert.equal(validatePartnerPlan({...plan,today:{...plan.today,items:[{...plan.today.items[0],goalId:'deleted-goal'}]}},state).today.items.length,0);
const misleadingAi={today:{items:plan.today.items.map(item=>({...item,durationMinutes:999}))},weeks:plan.weeks.map(week=>({...week,items:week.items.map(item=>({...item,durationMinutes:1}))}))};
const safeAi=mergeAiPlan(misleadingAi,plan,state);
assert.deepEqual(safeAi.today.items.map(i=>i.durationMinutes),plan.today.items.map(i=>i.durationMinutes),'AI는 계산된 시간을 덮어쓸 수 없다');
assert.deepEqual(safeAi.weeks.map(w=>w.totalMinutes),plan.weeks.map(w=>w.totalMinutes));
let adjustable=createPlanVersion({...state,cbtStudySessions:[]},plan,{activate:true});
const adjustId=getActivePartnerPlan(adjustable).today.items[0].id;
adjustable=adjustTodayPlanItem(adjustable,adjustId,'skip');
assert.equal(getActivePartnerPlan(adjustable).today.items.find(i=>i.id===adjustId).status,'skipped');
adjustable=createPlanVersion(adjustable,buildDeterministicPlan(adjustable,{today:'2026-09-30'}),{activate:true});
assert.equal(getActivePartnerPlan(adjustable).today.items.find(i=>i.goalId===plan.today.items[0].goalId).status,'skipped','재계획해도 오늘 건너뛰기를 유지');
const smallId=getActivePartnerPlan(adjustable).today.items[1].id;
for(let i=0;i<8;i++) adjustable=adjustTodayPlanItem(adjustable,smallId,'reduce');
assert.equal(getActivePartnerPlan(adjustable).today.items.find(i=>i.id===smallId).durationMinutes,15,'15분 항목 줄이기가 20분으로 늘어나면 안 된다');
let rest=setPartnerDayOff(createPlanVersion({...state,cbtStudySessions:[]},plan,{activate:true}),'2026-09-30',true);
assert.equal(getActivePartnerPlan(rest).today.items.length,0);
rest=setPartnerDayOff(rest,'2026-09-30',false);
assert.ok(getActivePartnerPlan(rest).today.items.length>0,'휴식 해제 후 오늘 계획 복구');
for (const week of plan.weeks) {
  const dailyTotal=Object.entries(week.dailyAllocations).reduce((total,[date,goals])=> {
    const minutes=Object.values(goals).reduce((sum,value)=>sum+value,0);
    assert.ok(minutes<=availableMinutesForDate(state.profile,date),'날짜별 가능 시간을 넘지 않는다');
    for(const [goalId,amount] of Object.entries(goals)) {
      const goal=state.certificateGoals.find(g=>g.id===goalId);
      assert.ok(date>=goal.startDate && date<=goal.examDate && amount>=15);
    }
    return total+minutes;
  },0);
  assert.equal(dailyTotal,week.totalMinutes,'주간 합계는 날짜별 실제 배치의 합과 같다');
  for(const goal of state.certificateGoals) assert.equal(week.items.filter(i=>i.goalId===goal.id).reduce((s,i)=>s+i.durationMinutes,0),Object.values(week.dailyAllocations).reduce((s,day)=>s+(day[goal.id]||0),0));
}
assert.equal(plan.today.totalMinutes,Object.values(plan.weeks[0].dailyAllocations['2026-09-30']).reduce((s,v)=>s+v,0));
assert.deepEqual(plan.weeks.at(-1).dailyAllocations['2026-10-11'],{},'토요일 마감 목표에 일요일 시간을 빌려 쓰지 않는다');
